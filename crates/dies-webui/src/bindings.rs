//! TypeScript bindings for the web UI, rendered as one self-contained file
//! (`webui/src/bindings.ts`) by the `gen-bindings` binary.
//!
//! The file holds every `#[derive(TS)]` type reachable from [`visit_roots`]: the
//! WebSocket message and the bodies/responses of the HTTP API. Types nested in
//! those (all of `dies-core`'s UI types) follow from their fields, so a new
//! type only needs registering here if the frontend uses it without it being
//! part of any message.

use std::{
    any::TypeId,
    collections::{BTreeMap, HashSet},
};

use dies_core::{RoleType, TeamData};
use ts_rs::{Config, TypeVisitor, TS};

use crate::{
    notebooks::{Notebook, NotebookDoc, NotebookSummary},
    routes::{LogNotebook, OpenLogNotebookBody},
    BasestationResponse, ExecutorInfoResponse, ExecutorSettingsResponse, GetDebugMapResponse,
    LogsResponse, PostExecutorSettingsBody, PostUiCommandBody, PostUiModeBody, SaveSnapshotBody,
    SettingsSnapshotsResponse, SnapshotsResponse, StrategiesResponse, UiStatus, UiWorldState,
    VaultLogsResponse, VaultOpenBody, VaultPushBody, VaultPushResponse, WsMessage,
};

const HEADER: &str = "\
// Generated by `cargo run -p dies-webui --bin gen-bindings` from the Rust types in
// dies-core and dies-webui (see crates/dies-webui/src/bindings.rs). Do not edit.
";

/// Renders `bindings.ts`: the header, then each type's docs and declaration,
/// sorted by name.
pub fn render() -> String {
    let cfg = Config::new().with_large_int("number");
    let mut collector = Collector {
        cfg: &cfg,
        seen: HashSet::new(),
        decls: BTreeMap::new(),
    };
    visit_roots(&mut collector);

    let mut out = HEADER.to_owned();
    for decl in collector.decls.values() {
        out.push('\n');
        out.push_str(decl);
        out.push('\n');
    }
    out
}

fn visit_roots(v: &mut impl TypeVisitor) {
    v.visit::<WsMessage<'static>>();
    v.visit::<UiStatus>();
    v.visit::<UiWorldState>();
    v.visit::<PostUiCommandBody>();
    v.visit::<PostUiModeBody>();
    v.visit::<ExecutorInfoResponse>();
    v.visit::<ExecutorSettingsResponse>();
    v.visit::<PostExecutorSettingsBody>();
    v.visit::<GetDebugMapResponse>();
    v.visit::<BasestationResponse>();
    v.visit::<StrategiesResponse>();
    v.visit::<SnapshotsResponse>();
    v.visit::<SaveSnapshotBody>();
    v.visit::<SettingsSnapshotsResponse>();
    v.visit::<LogsResponse>();
    v.visit::<VaultLogsResponse>();
    v.visit::<VaultPushBody>();
    v.visit::<VaultPushResponse>();
    v.visit::<VaultOpenBody>();
    v.visit::<Notebook>();
    v.visit::<NotebookDoc>();
    v.visit::<NotebookSummary>();
    v.visit::<LogNotebook>();
    v.visit::<OpenLogNotebookBody>();
    // Used by the frontend or the notebook prelude (`dies-notebook/src/prelude.d.ts`)
    // without being part of any message.
    v.visit::<RoleType>();
    v.visit::<TeamData>();
}

/// Collects the declaration of every exportable type it visits, plus its
/// dependencies (mirroring ts-rs's own `export_all`).
struct Collector<'a> {
    cfg: &'a Config,
    seen: HashSet<TypeId>,
    decls: BTreeMap<String, String>,
}

impl TypeVisitor for Collector<'_> {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        // Primitives and wrappers (`Option`, `Vec`, ...) have no declaration.
        if T::output_path().is_none() || !self.seen.insert(TypeId::of::<T>()) {
            return;
        }
        let decl = format!(
            "{}export {}",
            T::docs().unwrap_or_default(),
            T::decl_concrete(self.cfg)
        );
        let name = T::ident(self.cfg);
        let clash = self.decls.insert(name.clone(), decl);
        assert!(clash.is_none(), "two Rust types export as `{name}`");
        T::visit_dependencies(self);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn render_is_a_single_self_contained_file() {
        let out = render();
        assert_eq!(out, render());
        assert!(out.starts_with(HEADER));
        assert!(!out.contains("import "));
        assert!(!out.contains("bigint"));
        for alias in [
            "export type Vector2 = [number, number];",
            "export type Vector3 = [number, number, number];",
            "export type Duration = number;",
            "export type PlayerId = number;",
            "export type ParamValue = ",
        ] {
            assert!(out.contains(alias), "missing `{alias}`");
        }
    }
}
